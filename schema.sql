CREATE TABLE VOUCHER_CONFIG (
 VOUCHER_CONFIG VARCHAR2(128) PRIMARY KEY,
 CAMPANA_VOUCHER VARCHAR2(300) NOT NULL,
 FECHA_INICIO DATE NOT NULL,
 FECHA_FIN DATE NOT NULL,
 ACTIVO NUMBER(1) DEFAULT 1 CHECK (ACTIVO IN (0,1))
);

CREATE TABLE VOUCHERS (
 ID VARCHAR2(128) PRIMARY KEY,
 VOUCHER_CONFIG VARCHAR2(128), CAMPANA_VOUCHER VARCHAR2(300),
 CODE VARCHAR2(300), PROFORMA VARCHAR2(128), AMOUNT NUMBER(19,4),
 BRANCH_OFFICE VARCHAR2(128), ADDITIONAL VARCHAR2(4000),
 GENERATED TIMESTAMP WITH TIME ZONE, PROFORMA_USED VARCHAR2(128),
 BRANCH_OFFICE_USED VARCHAR2(128), USED TIMESTAMP WITH TIME ZONE,
 EXPIRATION TIMESTAMP WITH TIME ZONE,
 DNI VARCHAR2(128), CLIENT_ID VARCHAR2(128), CORE_CLIENT_ID VARCHAR2(128),
 KIND VARCHAR2(128), COMPANY VARCHAR2(128), KIND_LABEL VARCHAR2(300),
 COMPANY_LABEL VARCHAR2(300), STATUS_LABEL VARCHAR2(300),
 FECHA_CARGA TIMESTAMP WITH TIME ZONE
);

CREATE TABLE VOUCHER_STAGE (
 RUN_ID VARCHAR2(36) NOT NULL, ID VARCHAR2(128),
 VOUCHER_CONFIG VARCHAR2(128), CAMPANA_VOUCHER VARCHAR2(300),
 CODE VARCHAR2(300), PROFORMA VARCHAR2(128), AMOUNT NUMBER(19,4),
 BRANCH_OFFICE VARCHAR2(128), ADDITIONAL VARCHAR2(4000),
 GENERATED TIMESTAMP WITH TIME ZONE, PROFORMA_USED VARCHAR2(128),
 BRANCH_OFFICE_USED VARCHAR2(128), USED TIMESTAMP WITH TIME ZONE,
 EXPIRATION TIMESTAMP WITH TIME ZONE,
 DNI VARCHAR2(128), CLIENT_ID VARCHAR2(128), CORE_CLIENT_ID VARCHAR2(128),
 KIND VARCHAR2(128), COMPANY VARCHAR2(128), KIND_LABEL VARCHAR2(300),
 COMPANY_LABEL VARCHAR2(300), STATUS_LABEL VARCHAR2(300),
 STAGED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_VOUCHER_STAGE_RUN_ID ON VOUCHER_STAGE(RUN_ID, ID);

